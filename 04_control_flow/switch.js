const month = "march" // 3

switch (month) {
  case "jan": // 1 if number 
    console.log("January");
    break;
  case "feb":
    console.log("Febuary");
    break;
  case "march":
    console.log("March");
    break;
  case "apr":
    console.log("April");
    break;
  case "may":
    console.log("May");
    break;
  case "june":
    console.log("June");
    break;

  default:
    console.log("default case match");
    break;
}